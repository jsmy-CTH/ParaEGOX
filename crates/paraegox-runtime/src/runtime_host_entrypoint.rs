/// Runs the exact RuntimeHost executable mode selected by process arguments.
///
/// An empty argument list starts the existing RuntimeHost process. Unknown,
/// missing, additional, or non-canonical command arguments fail closed before
/// any file or Runtime state mutation. The two metadata arguments are not CLI
/// or configuration inputs: the `paraegox-runtime-host` composition root passes
/// constants generated by its own build script and embedded in that final
/// executable. A different Rust caller necessarily creates a different binary
/// and is not an alternate metadata path for the deployed RuntimeHost artifact.
pub fn run_runtime_host_entrypoint(
    final_executable_build_instance_id: [u8; 32],
    final_executable_target_triple: &'static str,
) -> Result<(), RuntimeHostEntrypointError> {
    let embedded_metadata = RuntimeHostEmbeddedBuildMetadataV1::from_final_executable(
        final_executable_build_instance_id,
        final_executable_target_triple,
    );
    let command = parse_runtime_host_command(env::args_os().skip(1))?;
    match command {
        RuntimeHostCommand::Run => run_runtime_host_process().map_err(Into::into),
        #[cfg(unix)]
        RuntimeHostCommand::ReleaseDescriptor { descriptor_output } => {
            run_release_descriptor(embedded_metadata, descriptor_output)
        }
        #[cfg(any(target_os = "linux", all(test, unix)))]
        RuntimeHostCommand::Install(arguments) => run_install(embedded_metadata, *arguments),
        #[cfg(any(target_os = "linux", all(test, unix)))]
        RuntimeHostCommand::ServeBootstrap(arguments) => {
            run_bootstrap_service(embedded_metadata, *arguments)
        }
        #[cfg(any(target_os = "linux", all(test, unix)))]
        RuntimeHostCommand::MigrateJournalV3ToV4(arguments) => {
            run_journal_v3_to_v4_migration(*arguments)
        }
        #[cfg(any(target_os = "linux", all(test, unix)))]
        RuntimeHostCommand::MigrateJournalV4ToV5(arguments) => {
            run_journal_v4_to_v5_migration(*arguments)
        }
        #[cfg(all(unix, not(target_os = "linux"), not(test)))]
        RuntimeHostCommand::Install(_)
        | RuntimeHostCommand::ServeBootstrap(_)
        | RuntimeHostCommand::MigrateJournalV3ToV4(_)
        | RuntimeHostCommand::MigrateJournalV4ToV5(_) => {
            Err(RuntimeHostEntrypointFailure::UnsupportedPlatform.into())
        }
        #[cfg(not(unix))]
        RuntimeHostCommand::ReleaseDescriptor { .. }
        | RuntimeHostCommand::Install(_)
        | RuntimeHostCommand::ServeBootstrap(_)
        | RuntimeHostCommand::MigrateJournalV3ToV4(_)
        | RuntimeHostCommand::MigrateJournalV4ToV5(_) => {
            Err(RuntimeHostEntrypointFailure::UnsupportedPlatform.into())
        }
    }
}

