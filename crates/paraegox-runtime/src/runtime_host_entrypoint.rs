const RELEASE_DESCRIPTOR_COMMAND: &str = "release-descriptor-v1";
const INSTALL_COMMAND: &str = "install-v1";
const SERVE_BOOTSTRAP_COMMAND: &str = "serve-bootstrap-v1";
