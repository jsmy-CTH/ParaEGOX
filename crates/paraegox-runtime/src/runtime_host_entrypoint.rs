                assert_parse_rejected_without_path_mutation(
                    uppercase,
                    &state_directory,
                    &evidence_directory,
                );

                let mut wrong_width = valid.clone();
                wrong_width[field_index] = os(&"44".repeat(31));
                assert_parse_rejected_without_path_mutation(
                    wrong_width,
                    &state_directory,
                    &evidence_directory,
                );

                let mut prefixed = valid.clone();
